const CALM_LINES = ['Все дела сделаны. Даже я доволен.', 'Непривычно, но приятно.'];

export function getGnomeState(focusTask) {
  if (!focusTask) return { stage: null, lines: CALM_LINES };
  const stage = Math.min(STAGES.length, Math.max(1, focusTask.snooze_count + 1));
  const lines = STAGES[stage - 1].lines.map((l) => l.replaceAll('{title}', focusTask.title));
  return { stage, lines };
}
